#include <bits/stdc++.h>
using namespace std;

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int T;
    cin >> T;
    while (T--) {
        int n;
        cin >> n;
        string s;
        cin >> s;
        int N = (1 << n) - 1;

        vector<int> b(N + 1, 0);   // 答案：b[x]=0 表示第 x 次操作跳过，否则 b[x]=y
        vector<int> cur(N + 1, 0); // 每个位置的当前值（记录未来位置被提前翻转的情况）
        for (int i = 1; i <= N; ++i) cur[i] = s[i - 1] - '0';

        int pos = -1; // 已扫描区间内唯一可能为 1 的位置，不存在则为 -1
        for (int i = 1; i <= N; ++i) {
            if (cur[i] == 0) {
                continue; // 当前位为 0，跳过第 i 次操作
            }
            if (pos == -1) {
                pos = i; // 第一个 1，记下待处理位置，跳过操作
                continue;
            }
            // 当前位为 1 且已有 pos：执行第 i 次操作，翻转 (i, pos, i^pos)
            b[i] = pos;
            int z = i ^ pos;
            cur[i] ^= 1;
            cur[pos] ^= 1;
            cur[z] ^= 1; // z 可能是未来位置，必须更新 cur 以便后续扫描
            if (z < i) pos = z;   // z 在已扫区间内（原本为 0），成为新的唯一 1
            else pos = -1;        // z 在未来，已扫区间全部清零
        }

        for (int i = 1; i <= N; ++i)
            cout << b[i] << (i == N ? '\n' : ' ');
    }
    return 0;
}

/* ============================================================================
 * 完整思路整理
 * ============================================================================
 *
 * 【目标】对长度为 N = 2^n - 1 的 01 串 s，进行编号 x = 1..N 的操作。
 *         第 x 次操作可选“跳过”，或“翻转 (x, y, z)”，其中 y,z ∈ [1,N]、y!=z、
 *         且 x = y^z（按位异或）。要求最终全串至多只有一个位置为 1。
 *
 * 一、核心不变量：所有 1 位置的编号异或和不变
 *     一次翻转会同时翻转变换集合中的位置 x,y,z，异或和的变化量为
 *         x ^ y ^ z = x ^ y ^ (x^y) = 0
 *     因此“所有值为 1 的位置编号的异或和”始终保持不变。
 *     结论：若初始异或和非零，最终不可能全为 0，只能恰好留下一个 1，
 *           且这个 1 的位置就是初始的异或和。这正是“至多剩一个 1”的最优目标。
 *
 * 二、从小到大扫描构造（贪心）
 *     维护 pos：已扫描区间（1..i-1）内唯一可能为 1 的位置，不存在则为 -1。
 *     扫描 i = 1..N，cur[i] 为当前位置当前值：
 *       1) cur[i] == 0        -> 跳过操作 i；
 *       2) cur[i] == 1 且 pos == -1 -> 令 pos = i，跳过操作 i（把该 1 挂起）；
 *       3) cur[i] == 1 且 pos != -1 -> 执行操作 i，取 y = pos，z = i^pos，
 *          翻转 (i, pos, z)：
 *          - 若 z < i：z 在已扫区间内且原本为 0，翻转后成为区间内唯一的 1，
 *            故更新 pos = z；
 *          - 若 z > i：i 与 pos 都被翻回 0，已扫区间全部清零，故 pos = -1，
 *            而 z 是未来位置（被提前翻成 1），用 cur 数组记录下来，等扫描到它时
 *            自然会以 1 被处理。
 *
 *     为什么每次操作的 (y,z) 都合法：pos < i 且在 [1,N] 内，z = i^pos < 2^n，
 *     故 z ∈ [1,N]，且 y!=z、y^z = pos^(i^pos) = i。
 *
 * 三、为什么最终满足要求
 *     归纳可知：处理完前 i 位后，位置 1..i 中至多有一个 1（位于 pos，或无）。
 *     处理完全部 N 位后，整个串至多只有一个 1。每个操作编号至多使用一次，
 *     总复杂度 O(N)。
 *
 * 【复杂度】时间 O(N)，空间 O(N)。
 *           （操作数 N = 2^n - 1，总 N <= 2e6）
 * ========================================================================== */
