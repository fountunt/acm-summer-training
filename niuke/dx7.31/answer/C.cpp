#include <bits/stdc++.h>
using namespace std;

// 输出一行 B 个空格分隔的整数
static void emit(const vector<int>& v) {
    string line;
    for (int i = 0; i < (int)v.size(); ++i) {
        if (i) line += ' ';
        line += to_string(v[i]);
    }
    cout << line << '\n';
}

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int B;
    cin >> B;

    // 必要条件：B 必须为偶数且 >= 4（见文件末尾思路推导），否则无解
    if (B < 4 || (B & 1)) {
        cout << -1 << '\n';
        return 0;
    }

    // B = 4 时一般构造会因 a[2]=0 导致 r[2]=2=p[2] 冲突，单独给出一组合法构造
    if (B == 4) {
        emit({0, 1, 2, 3});
        emit({1, 3, 0, 2});
        emit({2, 0, 3, 1});
        return 0;
    }

    // ---------- B >= 6 偶数：按题解构造 ----------
    int n = B / 2;
    vector<int> q(B), a(B), r(B), d(B);

    for (int p = 0; p < B; ++p) {
        q[p] = (p - 2 + B) % B;              // q 是 (p-2) mod B，随 p 遍历即为排列
        a[p] = (p < n) ? 1 : 0;              // a 为进入该列的进位，先取前 n 个为 1
    }
    swap(a[1], a[n + 1]);                    // 交换 a1 与 a(n+1)：消除 p=r 冲突，
                                             // 且保证 a[p] + a[p+n] = 1（循环意义下），
                                             // 入进位总数恰好为 n
    for (int p = 0; p < B; ++p) {
        int s = p + q[p] + a[p];             // p + q + 进位 = r + B*d
        r[p] = s % B;
        d[p] = s / B;                        // 出进位（0 或 1）
    }

    // 每列看成一条有向边 a[p] -> d[p]
    // 按出进位 / 入进位分类，用于构造欧拉回路
    vector<int> e00, e01, e10, e11;          // 0->0, 0->1, 1->0, 1->1
    for (int p = 0; p < B; ++p) {
        if (a[p] == 0 && d[p] == 0) e00.push_back(p);
        else if (a[p] == 0 && d[p] == 1) e01.push_back(p);
        else if (a[p] == 1 && d[p] == 0) e10.push_back(p);
        else e11.push_back(p);
    }

    // 相邻列要求“出进位 = 下一列入进位”，即边首尾相接
    // 因 sum(a) = sum(d) = n，两顶点图出入平衡；且 p=1 恒为 0->1 边保证连通
    // 从 0 出发走欧拉回路，得到从低位到高位的列顺序
    vector<int> col;                         // 回路顺序：低位在前，高位在后
    for (int p : e00) col.push_back(p);      // 0 处的自环先走
    for (int j = 0; j < (int)e01.size(); ++j) {
        col.push_back(e01[j]);               // 0 -> 1
        if (j == 0)
            for (int p : e11) col.push_back(p); // 第一次到 1 时走完 1 的自环
        col.push_back(e10[j]);               // 1 -> 0
    }

    // 输出时高位在前（第 1 位权重 B^(B-1)），所以把回路倒序作为输出
    vector<int> P(B), Q(B), R(B);
    for (int i = 0; i < B; ++i) {
        int p = col[B - 1 - i];
        P[i] = p;
        Q[i] = q[p];
        R[i] = r[p];
    }
    emit(P);
    emit(Q);
    emit(R);
    return 0;
}

/* ============================================================================
 * 完整思路整理
 * ============================================================================
 *
 * 【目标】构造 0..B-1 的三个排列 P,Q,R，满足 [P]B + [Q]B = [R]B（B 进制加法），
 *         且每一列 p_i, q_i, r_i 两两不同。
 *
 * 一、必要条件：B 必须为偶数且 B >= 4
 *     设进入第 j 位（从 0 开始，0 为最低位）的进位为 c_j，则
 *         p_j + q_j + c_j = r_j + B * c_{j+1},   c_0 = c_B = 0
 *     三个排列的数位和均为 S = B(B-1)/2。对所有列求和，设内部进位总数 C = sum(c_1..c_{B-1})：
 *         2S + C = S + B*C  =>  C = S/(B-1) = B/2
 *     所以 B 必须为偶数。再结合“每列三数互异”只有 B >= 4 才可能。
 *     因此 B 为奇数或 B < 4 时输出 -1。
 *
 * 二、B = 4 特判
 *     一般构造在 B=4 时会出现 a[2]=0、r[2]=2=p[2] 的冲突（见下），
 *     故单独给出暴力搜索得到的一组合法构造：
 *         P = (0,1,2,3), Q = (1,3,0,2), R = (2,0,3,1)
 *
 * 三、B >= 6 偶数的构造（按列构造）
 *     用 p = 0..B-1 标识列，令：
 *         q_p = (p-2) mod B
 *         a_p = 1  当 p < n，否则 0      （n = B/2）
 *         再交换 a_1 与 a_{n+1}（循环意义下）
 *     交换后 a_p + a_{p+n} = 1，且入进位恰有 n 个为 1。
 *     令 s_p = p + q_p + a_p，则
 *         r_p = s_p mod B,   d_p = floor(s_p / B)（出进位，必为 0 或 1）
 *
 *     (1) 为什么 Q 是排列：q_p = (p-2) mod B 是 p 的平移，显然是排列。
 *     (2) 为什么 R 是排列：r_p ≡ 2p - 2 + a_p (mod B)。把 p=x 与 p=x+n 配对，
 *         由 a_x + a_{x+n} = 1 得 {r_x, r_{x+n}} = {2x-2, 2x-1} (mod B)，
 *         即每组给出相邻的奇偶两个数，x=0..n-1 恰好覆盖 0..B-1，故 R 是排列。
 *     (3) 为什么列内互异：
 *         - p != q_p：等价于 B | 2，B>=4 时不可能。
 *         - p != r_p：等价于 p ≡ 2 - a_p (mod B)，只可能 p=1（需 a_1=1）或 p=2（需 a_2=0）。
 *           交换 a_1、a_{n+1} 使 a_1=0，消掉 p=1；而 B>=6 时 n>=3 故 a_2=1，消掉 p=2。
 *         - q_p != r_p：等价于 p + a_p ≡ 0 (mod B)，因 a_p∈{0,1} 且端点 a_0=1、a_{B-1}=0，不可能。
 *
 * 四、恢复列顺序（欧拉回路）
 *     每列看成有向边 a_p -> d_p（起点=入进位，终点=出进位）。
 *     相邻两列必须满足“前一列出进位 = 后一列入进位”，即边首尾相接成一条链。
 *     因为 sum(a) = sum(d) = n = B/2，两顶点有向多重图出入度平衡；
 *     且 p=1 恒有 a_1=0、d_1=1（s_1 = 1+(B-1)+0 = B），保证存在 0->1 边，图连通。
 *     因此从顶点 0 出发求欧拉回路，即得到从低位到高位的列顺序。
 *     最后把列序倒过来输出（高位在前），即得到合法的 P,Q,R。
 *
 * 【复杂度】时间 O(B)，空间 O(B)。B <= 1e6 可轻松通过。
 * ========================================================================== */
