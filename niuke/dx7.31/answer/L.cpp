#include <bits/stdc++.h>
using namespace std;

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int T;
    cin >> T;
    while (T--) {
        int n, m;
        cin >> n >> m;
        vector<vector<long long>> a(n + 1, vector<long long>(m + 1));
        for (int i = 1; i <= n; ++i)
            for (int j = 1; j <= m; ++j)
                cin >> a[i][j];

        // 单行 / 单列：唯一路径覆盖整行(列)，每次操作所有格子一起 +1，差值永不改变
        if (n == 1 || m == 1) {
            bool same = true;
            for (int i = 1; i <= n && same; ++i)
                for (int j = 1; j <= m && same; ++j)
                    if (a[i][j] != a[1][1]) same = false;
            cout << (same ? 0 : -1) << '\n';
            continue;
        }

        // 每条路径必过 (1,1)，第二步必过 (1,2) 或 (2,1)，可唯一消元出候选解：
        //   K = a12 + a21 - 2*a11（操作次数），X = a11 + K（最终值）
        long long K = a[1][2] + a[2][1] - 2LL * a[1][1];
        if (K < 0) { cout << -1 << '\n'; continue; }
        long long X = a[1][1] + K;

        // 每个格子需被覆盖 X - a[i][j] 次，必须非负
        bool ok = true;
        for (int i = 1; i <= n && ok; ++i)
            for (int j = 1; j <= m && ok; ++j)
                if (X - a[i][j] < 0) ok = false;
        if (!ok) { cout << -1 << '\n'; continue; }

        // ---- 按反斜线 i + j = s 分层做流量分配 ----
        // cur[r] = 当前层第 r 行的需求量；格子不存在则为 0（视为无流量）
        vector<long long> cur(n + 1), nxt(n + 1);   // 已清零
        cur[1] = X - a[1][1];                       // 初始层 s=2 只有 (1,1)，其余行需求为 0

        for (int s = 2; s < n + m && ok; ++s) {
            // 下一层 s+1 的需求量
            for (int r = 1; r <= n; ++r) {
                int c = s + 1 - r;
                nxt[r] = (c >= 1 && c <= m) ? X - a[r][c] : 0;
            }

            // 贪心分配：carry = 上方流下来的流量 g_{r-1}。
            // 第 r 行下一层的需求由两部分补足：本层第 r 行"直走"f_r + 上方流入 carry。
            // 因需求值固定，f_r 被唯一确定：f_r = nxt[r] - carry，
            // 本层第 r 行剩余流量 cur[r] - f_r 继续流向下一层第 r+1 行。
            long long carry = 0;
            for (int r = 1; r <= n && ok; ++r) {
                long long need = nxt[r] - carry;              // 必须由本行直走的流量
                if (need < 0 || need > cur[r]) ok = false;    // 超出本行可提供的流量
                else carry = cur[r] - need;                   // 剩余流量向下
            }
            if (carry != 0) ok = false;                       // 最后一行不能再向下
            cur.swap(nxt);
        }

        cout << (ok ? K : -1) << '\n';
    }
    return 0;
}

/* ============================================================================
 * 完整思路整理
 * ============================================================================
 *
 * 【目标】可任意多次选择一条从 (1,1) 到 (n,m) 的单调路径（只向右/向下），
 *         把路径上所有格子 +1，使整个矩阵最终全相等，求最少操作次数，无解输出 -1。
 *
 * 一、候选解唯一（消元）
 *     每条路径必过 (1,1)，且第二步必过 (1,2) 或 (2,1)（n,m >= 2 时）。
 *     设最终值为 X、操作次数为 K：
 *         X = a11 + K                    （(1,1) 被所有 K 条路径覆盖）
 *         2X = a12 + a21 + K             （每条路径恰经过 (1,2)、(2,1) 之一）
 *     消元得唯一候选：
 *         K = a12 + a21 - 2*a11，  X = a11 + K。
 *     故 K < 0 或任一格子需要覆盖的次数 X - a[i][j] < 0 时无解。
 *
 * 二、可行性：按反斜线分层做流量分配
 *     把格点按 i + j = s 分层。每条路径在每个层上恰经过一个格子，
 *     因此"格子 (i,j) 被覆盖 X - a[i][j] 次"等价于每层上的一个流量分配问题：
 *     当前层第 r 行的流量 b_r 只能流向下一层的第 r 行（直走）或第 r+1 行（向下）。
 *     设下一层第 r 行的需求为 c_r，从上方流入的流量为 carry = g_{r-1}，则
 *         第 r 行的需求被"直走流量 f_r + 上方流入 carry"补足，即 f_r = c_r - carry，
 *         于是剩余流量 g_r = b_r - f_r 继续向下。
 *     由于 c_r、b_r 全部固定，f_r 与 g_r 被逐行唯一确定（不存在选择空间），
 *     只需依次检查：
 *         - f_r >= 0 且 f_r <= b_r（本行能提供的流量足够且不为负）；
 *         - 最后一行结束时 g_n = 0（最后一行不能再向下流）。
 *     任一步失败则无解，否则 K 即为最少操作次数。
 *     等价于题解的前缀和条件 B_{r-1} <= C_r <= B_r。
 *
 * 三、边界：单行 / 单列
 *     此时唯一路径覆盖整行/整列，每次操作所有格子一起 +1，元素间差值永不改变，
 *     因此仅当初始矩阵已全相等时有解（答案为 0），否则 -1。
 *
 * 【复杂度】时间 O(n*m)，空间 O(n*m)（存储矩阵；分配部分仅需 O(n)）。
 *           T <= 5000，sum n, sum m <= 5000，可轻松通过。
 * ========================================================================== */
